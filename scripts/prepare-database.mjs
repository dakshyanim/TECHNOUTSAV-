import { readFile, readdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export async function buildDatabaseSetup() {
  const directory = new URL('../supabase/migrations/', import.meta.url);
  const migrations = (await readdir(directory)).filter(name => name.endsWith('.sql')).sort();
  const parts = [];
  for (const name of migrations) {
    const sql = await readFile(new URL(name, directory), 'utf8');
    // The combined setup owns one transaction. Migration files remain unchanged.
    const body = sql.replace(/^\s*(?:begin|commit);\s*$/gim, '');
    parts.push(`-- Migration: ${name}\n${body.trim()}\n`);
  }
  const seed = await readFile(new URL('../supabase/seed.sql', import.meta.url), 'utf8');
  return `-- Techno Utsav: FRESH Supabase database setup.
-- Generated by npm run prepare:database; do not hand-edit this generated file.
-- Run once as the project owner in Supabase SQL Editor. Contains no secrets.
-- Existing app tables cause an error BEFORE any changes. Never drop event data.
begin;
select pg_advisory_xact_lock(173627,2);
do $setup$
begin
  if exists (
    select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
    where n.nspname='public' and c.relname=any(array[
      'participants','questions','submissions','participant_sessions',
      'admin_login_attempts','api_request_limits','revoked_admin_sessions',
      'leaderboard_notification_gate'
    ])
  ) then
    raise exception 'Application tables already exist. Apply only missing versioned migrations; do not rerun fresh setup.';
  end if;
  if to_regprocedure('realtime.send(jsonb,text,text,boolean)') is null then
    raise exception 'Supabase realtime.send is missing. Use a Supabase project with database Broadcast support.';
  end if;
end;
$setup$;

${parts.join('\n')}
-- Ten sample questions; QR challenge codes Q001 through Q010.
${seed.trim()}

-- This record prevents a future Supabase CLI migration run replaying this setup.
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (
  version text not null primary key, statements text[], name text
);
${migrations.map(name => {
    const [version] = name.split('_');
    const title = name.slice(version.length + 1, -4);
    return `insert into supabase_migrations.schema_migrations(version,name) values('${version}','${title}') on conflict(version) do nothing;`;
  }).join('\n')}
commit;

-- Safe summary only: no answers, participant data or session tokens.
select public.health_check() as database_ok,
  (select count(*) from public.questions) as question_count,
  (select count(*) from public.questions where active) as active_questions,
  (select count(*) from supabase_migrations.schema_migrations where version in (${migrations.map(name=>`'${name.split('_')[0]}'`).join(',')})) as migrations_applied;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(new URL('../supabase/setup.sql', import.meta.url), await buildDatabaseSetup(), 'utf8');
  console.log('Prepared supabase/setup.sql: all migrations + sample questions, one transaction, guarded against existing data.');
}
