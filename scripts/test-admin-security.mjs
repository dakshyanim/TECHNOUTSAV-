import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createPasswordHash,verifyAdminPassword,createAdminToken,verifyAdminToken,validAdminConfig,ADMIN_SESSION_SECONDS } from '../src/lib/admin-crypto.ts';
import { csvCell,makeCsv } from '../src/lib/csv.ts';
import { validateQuestion } from '../src/lib/admin-question.ts';
import { formatUtc } from '../src/lib/utc.ts';

const password='Test admin password, not a live credential';
const hash=await createPasswordHash(password),secret=randomBytes(32).toString('hex');
assert.ok(validAdminConfig(hash,secret));
assert.ok(await verifyAdminPassword(password,hash));
assert.equal(await verifyAdminPassword('incorrect',hash),false);
assert.equal(validAdminConfig(hash,'short'),false);
const token=createAdminToken(hash,secret,1000);
assert.ok(verifyAdminToken(token,hash,secret,1001));
assert.equal(verifyAdminToken(token,hash,secret,1000+ADMIN_SESSION_SECONDS),false);
assert.equal(verifyAdminToken(token,hash,secret,900),false);
assert.equal(verifyAdminToken(token+'a',hash,secret,1001),false);
assert.equal(verifyAdminToken(randomBytes(32).toString('hex'),hash,secret,1001),false);
assert.equal(verifyAdminToken(token,hash,randomBytes(32).toString('hex'),1001),false);
assert.equal(verifyAdminToken(token,await createPasswordHash(password),secret,1001),false);
const question={question:'Which structure?',choices:['Stack','Queue','Tree','Graph'],correct_choice:0,points:10,active:true};
assert.deepEqual(validateQuestion(question),{question:question.question,choices:question.choices,correct_answer:'Stack',points:10,active:true});
for (const change of [{points:-1},{points:1.5},{points:10001},{active:'true'},{question:' '},{correct_choice:4},{correct_choice:-1},{choices:['A','A','B','C']},{choices:['A','B','C']},{choices:['A','B','C','']}]) assert.equal(validateQuestion({...question,...change}),null);
assert.equal(csvCell('=SUM(1,2)'), '"\'=SUM(1,2)"');
assert.equal(csvCell('  @danger'), '"\'  @danger"');
assert.equal(csvCell('A,"B"'),'"A,""B"""');
assert.ok(makeCsv(['Name'],[['Student']]).startsWith('\uFEFF'));
assert.equal(formatUtc('2026-10-09T09:00:00+05:30'),'2026-10-09T03:30:00.000Z');
console.log('PASS: password checks, signed admin sessions, expiry, tampering, rotation, participant token rejection, question validation and safe CSV escaping.');
